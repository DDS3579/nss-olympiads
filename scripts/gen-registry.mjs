#!/usr/bin/env node
/**
 * gen-registry.mjs — generates lib/data/registry.generated.ts with explicit
 * static imports (bundlers can't import dynamic JSON paths).
 * Run by "predev" and "prebuild". Missing optional files fall back to []/null.
 */
import fs from "node:fs";
import path from "node:path";

const root = "data/subjects";
const slugs = fs.existsSync(root)
  ? fs.readdirSync(root).filter((d) => fs.statSync(path.join(root, d)).isDirectory()).sort()
  : [];
const files = ["meta", "topics", "resources", "papers", "originals", "syllabus", "roadmap", "featured", "gaps"];

let out = "// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit\n";
slugs.forEach((s, i) =>
  files.forEach((f) => {
    if (fs.existsSync(path.join(root, s, `${f}.json`)))
      out += `import ${f}_${i} from "@/data/subjects/${s}/${f}.json";\n`;
  })
);

out += "\nexport const RAW = {\n";
slugs.forEach((s, i) => {
  out +=
    `  "${s}": {\n` +
    files
      .map((f) =>
        fs.existsSync(path.join(root, s, `${f}.json`))
          ? `    ${f}: ${f}_${i} as unknown,`
          : `    ${f}: ${f === "meta" ? "null" : "[]"} as unknown,`
      )
      .join("\n") +
    "\n  },\n";
});
out += "} as const;\n\nexport const SLUGS = " + JSON.stringify(slugs) + " as const;\n";

fs.mkdirSync("lib/data", { recursive: true });
fs.writeFileSync("lib/data/registry.generated.ts", out);
console.log("registry:", slugs.length ? slugs.join(", ") : "(no subjects yet)");